def _escape(text: str) -> str:
    """Basic HTML escaping."""
    return (
        text
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


def _format_takeaways(key_takeaways: List[str]) -> str:
    """Render key takeaways as an HTML section."""
    if not key_takeaways:
        return ""
    items = "\n".join(f"<li>{_escape(t)}</li>" for t in key_takeaways)
    return f"""<h2>Key Takeaways</h2>\n<ul class="takeaways">\n{items}\n</ul>"""


def _format_clauses(clauses: List[Dict[str, Any]]) -> str:
    """Render extracted clauses as an HTML table section."""
    if not clauses:
        return ""
    rows = ""
    for c in clauses:
        rows += (
            f'<tr><td class="category-badge">{_escape(str(c.get("category", "")))}</td>'
            f'<td class="clause-text">{_escape(str(c.get("clause_text", ""))[:400])}</td>'
            f'<td>{_escape(str(c.get("page_number", "-")))}</td></tr>\n'
        )
    return (
        '<h2>Extracted Clauses</h2>\n<table>\n'
        '<thead><tr><th style="width:20%">Category</th><th style="width:70%">Clause Text</th>'
        '<th style="width:10%">Page</th></tr></thead>\n'
        f'<tbody>\n{rows}</tbody>\n</table>'
    )


def _format_entities(entities: List[Dict[str, Any]]) -> str:
    """Render extracted entities as a two-column grid."""
    if not entities:
        return ""
    cards = ""
    for e in entities:
        cards += (
            f'<div class="entity-card">'
            f'<div class="entity-type">{_escape(str(e.get("entity_type", "")))}</div>'
            f'<div class="entity-text">{_escape(str(e.get("text", "")))}</div>'
            f'</div>\n'
        )
    return f'<h2>Extracted Entities</h2>\n<div class="entities-grid">\n{cards}</div>'


def generate_pdf_report(
    document: Dict[str, Any],
    summary: Optional[Dict[str, Any]],
    clauses: List[Dict[str, Any]],
    entities: List[Dict[str, Any]],
) -> bytes:
    """
    Generate a professional PDF analysis report for a legal document.

    Primary renderer: WeasyPrint (requires native Pango/Cairo GTK libraries).
    Fallback renderer: PyMuPDF text-based PDF generation (always available).

    Args:
        document: Document metadata dict (filename, page_count, etc.)
        summary:  Summary dict (summary_text, key_takeaways, doc_type)
        clauses:  List of extracted clause dicts
        entities: List of extracted entity dicts

    Returns:
        Raw PDF bytes ready to stream to the client.
    """
    filename = document.get("filename", "document.pdf")
    page_count = document.get("page_count", 1)
    doc_type = "CONTRACT"
    if summary:
        doc_type = summary.get("doc_type", doc_type)
    generated_at = datetime.now(timezone.utc).strftime("%B %d, %Y at %H:%M UTC")

    summary_text = ""
    key_takeaways: List[str] = []
    if summary:
        summary_text = summary.get("summary_text", "")
        key_takeaways = summary.get("key_takeaways", [])

    formatted_summary = "</p><p>".join(
        _escape(p) for p in (summary_text or "No summary available.").split("\n\n")
        if p.strip()
    )

    html_content = _REPORT_HTML_TEMPLATE.format(
        filename=_escape(filename),
        generated_at=generated_at,
        page_count=page_count,
        doc_type=doc_type.capitalize(),
        summary_text=formatted_summary,
        takeaways_section=_format_takeaways(key_takeaways),
        clauses_section=_format_clauses(clauses),
        entities_section=_format_entities(entities),
    )

    # Primary path: WeasyPrint
    try:
        from weasyprint import HTML as WeasyHTML
        pdf_bytes = WeasyHTML(string=html_content, base_url=None).write_pdf()
        logger.info("PDF export completed via WeasyPrint for document: %s", filename)
        return pdf_bytes
    except ImportError:
        logger.warning("WeasyPrint not installed. Using PyMuPDF fallback renderer.")
    except Exception as weasy_err:
        logger.warning(
            "WeasyPrint rendering failed (%s). Falling back to PyMuPDF renderer.", weasy_err
        )

    # Fallback path: PyMuPDF text PDF
    return _generate_pdf_pymupdf(filename, generated_at, page_count, doc_type,
                                  summary_text, key_takeaways, clauses, entities)


def _generate_pdf_pymupdf(
    filename: str,
    generated_at: str,
    page_count: int,
    doc_type: str,
    summary_text: str,
    key_takeaways: List[str],
    clauses: List[Dict[str, Any]],
    entities: List[Dict[str, Any]],
) -> bytes:
    """Fallback PDF generator using PyMuPDF (always available)."""
    import fitz  # PyMuPDF

    doc = fitz.open()
    page = doc.new_page(width=595, height=842)

    margin_l, margin_r, margin_t = 60, 60, 60
    para_chars = 90

    def add_line(pg, text, x, y, fontsize=10, bold=False, color=(0, 0, 0)):
        fn = "hebo" if bold else "helv"
        pg.insert_text((x, y), text, fontsize=fontsize, fontname=fn, color=color)
        return y + fontsize + 4

    def section_header(pg, y, title):
        pg.draw_line((margin_l, y), (595 - margin_r, y), color=(0.87, 0.89, 0.94), width=0.5)
        y += 6
        return add_line(pg, title.upper(), margin_l, y, fontsize=8, bold=True, color=(0.18, 0.23, 0.43))

    def wrap_text(pg_ref, text, x, y, fontsize=9):
        """Word-wrap and render text; returns (page_ref, new_y)."""
        words = text.split()
        line_buf = []
        for word in words:
            line_buf.append(word)
            if len(" ".join(line_buf)) > para_chars:
                y = add_line(pg_ref, " ".join(line_buf[:-1]), x, y, fontsize=fontsize)
                line_buf = [word]
                if y > 810:
                    pg_ref = doc.new_page(width=595, height=842)
                    y = margin_t
        if line_buf:
            y = add_line(pg_ref, " ".join(line_buf), x, y, fontsize=fontsize)
        return pg_ref, y

    y = margin_t
    y = add_line(page, "AMICUS LEGAL INTELLIGENCE - ANALYSIS REPORT", margin_l, y,
                 fontsize=7, bold=True, color=(0.18, 0.23, 0.43))
    y = add_line(page, filename, margin_l, y, fontsize=13, bold=True)
    y = add_line(page, f"Generated: {generated_at}  |  {page_count} page(s)  |  {doc_type}", margin_l, y,
                 fontsize=8, color=(0.4, 0.4, 0.4))
    page.draw_line((margin_l, y + 2), (595 - margin_r, y + 2), color=(0.18, 0.23, 0.43), width=0.6)
    y += 14

    y = section_header(page, y, "Executive Summary")
    for para in (summary_text or "No summary available.").split("\n\n"):
        page, y = wrap_text(page, para.strip(), margin_l + 10, y)
        y += 4

    if key_takeaways:
        y += 6
        if y > 760:
            page = doc.new_page(width=595, height=842)
            y = margin_t
        y = section_header(page, y, "Key Takeaways")
        for t in key_takeaways:
            if y > 810:
                page = doc.new_page(width=595, height=842)
                y = margin_t
            y = add_line(page, f"  > {t[:120]}", margin_l + 8, y, fontsize=9)

    if clauses:
        y += 8
        if y > 750:
            page = doc.new_page(width=595, height=842)
            y = margin_t
        y = section_header(page, y, "Extracted Clauses")
        for c in clauses:
            if y > 790:
                page = doc.new_page(width=595, height=842)
                y = margin_t
            cat = c.get("category", "")
            pg_n = c.get("page_number", "-")
            y = add_line(page, f"{cat}  [Pg {pg_n}]", margin_l, y, fontsize=9, bold=True)
            excerpt = c.get("clause_text", "")[:200].replace("\n", " ")
            y = add_line(page, f"  {excerpt}...", margin_l + 8, y, fontsize=8.5, color=(0.25, 0.25, 0.25))
            y += 4

    if entities:
        y += 8
        if y > 750:
            page = doc.new_page(width=595, height=842)
            y = margin_t
        y = section_header(page, y, "Extracted Entities")
        for e in entities:
            if y > 810:
                page = doc.new_page(width=595, height=842)
                y = margin_t
            etype = e.get("entity_type", "")
            etext = e.get("text", "")
            y = add_line(page, f"  {etype}: {etext}", margin_l + 8, y, fontsize=9)

    for i in range(len(doc)):
        fpage = doc[i]
        fpage.insert_text(
            (margin_l, 828),
            f"Amicus Legal Intelligence - Informational Use Only - Page {i + 1} of {len(doc)}",
            fontsize=7, color=(0.6, 0.6, 0.6), fontname="helv"
        )

    buf = io.BytesIO()
    doc.save(buf)
    doc.close()
    return buf.getvalue()
