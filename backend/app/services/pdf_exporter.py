"""
PDF Report Exporter for Amicus Legal Text Analyzer
Generates a professional formatted PDF report for an analyzed document.
Uses WeasyPrint as primary renderer, falls back to PyMuPDF text-based
PDF generation when native GTK/Pango/Cairo libraries are not available
(typical on Windows environments without GTK runtime).
"""

import io
import logging
from datetime import datetime, timezone
from typing import List, Dict, Any, Optional

logger = logging.getLogger(__name__)

